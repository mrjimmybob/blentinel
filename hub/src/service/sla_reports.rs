//! M6-05: On-demand monthly SLA reports - printable HTML with availability % (proposal 0007, D-10)
//!
//! Generate availability reports for a check over a month.
//! Includes: % uptime, downtime events, compliance summary.

use anyhow::Result;
use chrono::{DateTime, Utc, prelude::*};
use serde::Serialize;
use sqlx::SqlitePool;

use crate::service::availability;

/// A monthly SLA report for one check.
#[derive(Debug, Clone, Serialize)]
pub struct SLAReport {
    pub check_id: String,
    pub check_name: String,
    pub month: String,
    pub year: i32,
    pub availability_pct: f64,
    pub downtime_minutes: i32,
    pub downtime_events: i32,
    pub sla_target_pct: f64,
    pub meets_sla: bool,
    pub generated_at: DateTime<Utc>,
}

/// Generate a monthly SLA report for a check.
pub async fn generate_monthly_report(
    pool: &SqlitePool,
    check_id: &str,
    check_name: &str,
    month: u32,
    year: i32,
    sla_target_pct: f64,
) -> Result<SLAReport> {
    // Calculate range: first day of month to first day of next month
    let first_of_month = Utc
        .with_ymd_and_hms(year, month, 1, 0, 0, 0)
        .single()
        .ok_or_else(|| anyhow::anyhow!("Invalid date"))?;

    let first_of_next = if month == 12 {
        Utc.with_ymd_and_hms(year + 1, 1, 1, 0, 0, 0).single()
    } else {
        Utc.with_ymd_and_hms(year, month + 1, 1, 0, 0, 0).single()
    }.ok_or_else(|| anyhow::anyhow!("Invalid date"))?;

    // Get availability %
    let avail_pct = availability::availability_pct(pool, check_id, first_of_month, first_of_next)
        .await?
        .unwrap_or(0.0);

    // Calculate downtime minutes and events (simplified: count Down buckets)
    // TODO: Integrate with actual incident tracking for accurate downtime_events
    let downtime_minutes = (((100.0 - avail_pct) / 100.0) * (30.0 * 24.0 * 60.0)) as i32;
    let downtime_events = if downtime_minutes > 0 { 1 } else { 0 }; // Placeholder

    let meets_sla = avail_pct >= sla_target_pct;

    Ok(SLAReport {
        check_id: check_id.to_string(),
        check_name: check_name.to_string(),
        month: format!("{:02}", month),
        year,
        availability_pct: (avail_pct * 10.0).round() / 10.0, // 1 decimal place
        downtime_minutes,
        downtime_events,
        sla_target_pct,
        meets_sla,
        generated_at: Utc::now(),
    })
}

/// Render SLA report as HTML (printable).
pub fn render_html(report: &SLAReport) -> String {
    let status_color = if report.meets_sla { "green" } else { "red" };
    let status_text = if report.meets_sla { "PASS" } else { "FAIL" };

    format!(
        r#"<!DOCTYPE html>
<html>
<head>
    <title>SLA Report - {}</title>
    <style>
        body {{ font-family: Arial, sans-serif; margin: 2cm; }}
        h1 {{ color: #333; }}
        .summary {{ border: 1px solid #ccc; padding: 10px; margin: 10px 0; }}
        .status {{ font-size: 24px; color: {}; font-weight: bold; }}
        .metric {{ margin: 5px 0; }}
        table {{ width: 100%; border-collapse: collapse; }}
        th, td {{ border: 1px solid #ddd; padding: 8px; text-align: left; }}
        @media print {{ body {{ margin: 0; }} }}
    </style>
</head>
<body>
    <h1>SLA Report: {}</h1>
    <p>Period: {}/{} | Generated: {}</p>

    <div class="summary">
        <div class="metric"><strong>Check:</strong> {}</div>
        <div class="metric"><strong>Availability:</strong> <span class="status">{:.1}%</span></div>
        <div class="metric"><strong>SLA Target:</strong> {:.1}%</div>
        <div class="metric"><strong>Status:</strong> <span class="status">{}</span></div>
        <div class="metric"><strong>Downtime:</strong> {} minutes ({} events)</div>
    </div>

    <h2>Summary</h2>
    <p>This check achieved {:.1}% availability in {}/{}, {} the SLA target of {:.1}%.</p>

    <footer style="border-top: 1px solid #ccc; margin-top: 2cm; padding-top: 1cm; color: #666; font-size: 12px;">
        <p>Automatically generated by Blentinel. Not an official SLA guarantee.</p>
    </footer>
</body>
</html>"#,
        report.check_name,
        status_color,
        report.check_name,
        report.month,
        report.year,
        report.generated_at.format("%Y-%m-%d %H:%M UTC"),
        report.check_name,
        report.availability_pct,
        report.sla_target_pct,
        status_text,
        report.downtime_minutes,
        report.downtime_events,
        report.availability_pct,
        report.month,
        report.year,
        if report.meets_sla { "meets" } else { "misses" },
        report.sla_target_pct,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_html_includes_check_name() {
        let report = SLAReport {
            check_id: "check-1".to_string(),
            check_name: "API Server".to_string(),
            month: "11".to_string(),
            year: 2026,
            availability_pct: 99.5,
            downtime_minutes: 7,
            downtime_events: 1,
            sla_target_pct: 99.0,
            meets_sla: true,
            generated_at: Utc::now(),
        };

        let html = render_html(&report);
        assert!(html.contains("API Server"));
        assert!(html.contains("99.5%"));
    }

    #[test]
    fn render_html_marks_pass_for_met_sla() {
        let report = SLAReport {
            check_id: "check-1".to_string(),
            check_name: "Test".to_string(),
            month: "11".to_string(),
            year: 2026,
            availability_pct: 99.5,
            downtime_minutes: 7,
            downtime_events: 1,
            sla_target_pct: 99.0,
            meets_sla: true,
            generated_at: Utc::now(),
        };

        let html = render_html(&report);
        assert!(html.contains("PASS"));
    }

    #[test]
    fn render_html_marks_fail_for_missed_sla() {
        let report = SLAReport {
            check_id: "check-1".to_string(),
            check_name: "Test".to_string(),
            month: "11".to_string(),
            year: 2026,
            availability_pct: 98.5,
            downtime_minutes: 21,
            downtime_events: 2,
            sla_target_pct: 99.0,
            meets_sla: false,
            generated_at: Utc::now(),
        };

        let html = render_html(&report);
        assert!(html.contains("FAIL"));
    }
}
